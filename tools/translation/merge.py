#!/usr/bin/env python3
"""merge.py — check translated batches and merge them into data/lang/<lang>.tsv.

Input: build/translation/out/*.tsv, lines "VA <TAB> TEXT" (the translator's output for a batch).
Each line is checked against the English original (common.problems): the game's codes (%s %d %mN% %w @@KEY #N)
kept, the byte cap of strings copied into fixed buffers, only characters the game can draw (Windows-1252).
Good lines go into data/lang/<lang>.tsv (VA <TAB> CAP <TAB> TEXT, sorted; a VA already there is replaced);
bad ones are listed in build/translation/merge-problems.txt and left out.

    python3 tools/translation/merge.py [--lang pt-br] [files...]
"""
import argparse
import glob
import os

from common import LANG_DIR, WORK, esc, load_strings, port_refs, problems, read_tsv, unesc

# typographic marks the original text never uses -> its plain style
PLAIN = {"“": '"', "”": '"', "‘": "'", "’": "'", "…": "...", "—": "-", "–": "-", " ": " "}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lang", default="pt-br")
    ap.add_argument("files", nargs="*")
    a = ap.parse_args()
    files = a.files or sorted(glob.glob(os.path.join(WORK, "out", "*.tsv")))

    rows = load_strings()
    _, capped = port_refs()
    os.makedirs(LANG_DIR, exist_ok=True)
    lp = os.path.join(LANG_DIR, a.lang + ".tsv")
    cur = read_tsv(lp) if os.path.exists(lp) else {}

    good, bad = 0, []
    for fn in files:
        for n, line in enumerate(open(fn, encoding="utf-8-sig"), 1):
            line = line.rstrip("\n").rstrip("\r")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            try:
                va = int(parts[0], 16)
            except ValueError:
                bad.append(f"{os.path.basename(fn)}:{n}: no VA: {line[:80]}")
                continue
            pt = unesc(parts[-1])
            for k, v in PLAIN.items():
                pt = pt.replace(k, v)
            if va not in rows:
                bad.append(f"{os.path.basename(fn)}:{n}: 0x{va:06x} is not a string of the game")
                continue
            en = rows[va]["text"]
            cap = int(rows[va]["bytes"]) if va in capped else 0
            p = problems(en, pt, cap)
            if p:
                bad.append(f"{os.path.basename(fn)}:{n}: 0x{va:06x}: " + "; ".join(p) + f"\n    EN: {en}\n    PT: {pt}")
                continue
            cur[va] = (cap, pt)
            good += 1

    with open(lp, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# CoopSummoners translation: {a.lang}.  VA <TAB> MAX BYTES (0 = any) <TAB> TEXT\n")
        f.write("# Machine translated, reviewed by hand over time.  Keep the game's codes: %n line break, %s / %d\n")
        f.write("# fields, @@KEY key names.  Generated by tools/translation/merge.py; edit via review.py.\n")
        for va in sorted(cur):
            c, t = cur[va]
            f.write(f"0x{va:06x}\t{c}\t{esc(t)}\n")
    pp = os.path.join(WORK, "merge-problems.txt")
    open(pp, "w", encoding="utf-8").write("\n".join(bad) + "\n")
    print(f"merged {good} lines from {len(files)} files; {len(cur)} strings in {lp}; "
          f"{len(bad)} problems" + (f" -> {pp}" if bad else ""))


if __name__ == "__main__":
    main()
